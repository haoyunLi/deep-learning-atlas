export function normalizeGlossaryText(value: string): string {
  return value
    .normalize("NFKC")
    .toLocaleLowerCase()
    .replace(/[^\p{L}\p{N}]/gu, "");
}
export function filterGlossary(
  query: string,
  group: GlossaryGroup | "all" = "all",
): GlossaryEntry[] {
  const words = query
    .trim()
    .split(/\s+/)
    .map(normalizeGlossaryText)
    .filter(Boolean);
  return glossaryEntries.filter(
    (entry) =>
      (group === "all" || entry.group === group) &&
      words.every((word) =>
        normalizeGlossaryText(
          [
            entry.chinese,
            entry.english,
            ...entry.aliases,
            entry.definition,
          ].join(" "),
        ).includes(word),
      ),
  );
}
