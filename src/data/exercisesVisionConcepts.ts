export const visionConceptExercises: Record<string, Exercise[]> =
  Object.fromEntries(
    pairs.map(([lessonId, ...prompts], lessonIndex) => [
      lessonId,
      prompts.map(
        ([question, correct, distractor1, distractor2, explanation], index) => {
          const kind = index === 0 ? "mechanism" : "decision";
          const answer = (lessonIndex + index) % 3;
          const options = [distractor1, distractor2];
          options.splice(answer, 0, correct);
          return {
            id: `${lessonId}-${kind}`,
            kind,
            question,
            options,
            answer,
            explanation,
          };
        },
      ),
    ]),
  );
