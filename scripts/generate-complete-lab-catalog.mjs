import { writeFileSync } from "node:fs";
import { createLoader } from "./lib/load-ts.mjs";

// Run explicitly after editing lab metadata. The browser imports only this small index.
const load = createLoader();
const groups = {
  ml: load("src/data/completeLabs/ml.ts").mlCompleteLabs,
  cv: load("src/data/completeLabs/cv.ts").cvCompleteLabs,
  rl: load("src/data/completeLabs/rl.ts").rlCompleteLabs,
};
const catalog = Object.fromEntries(
  Object.entries(groups).flatMap(([group, labs]) =>
    Object.entries(labs).map(([id, lab]) => [
      id,
      {
        group,
        label: lab.controls.map((c) => c.label).join(" / "),
        hint: lab.question,
      },
    ]),
  ),
);
writeFileSync(
  "src/data/completeLabCatalog.ts",
  "// Generated by scripts/generate-complete-lab-catalog.mjs; calculations load on demand.\n" +
    'export type CompleteLabGroup = "ml" | "cv" | "rl";\n' +
    "export const completeLabCatalog: Record<string, { group: CompleteLabGroup; label: string; hint: string }> = " +
    JSON.stringify(catalog, null, 2) +
    ";\n",
);
console.log(
  `Generated ${Object.keys(catalog).length} lightweight catalogue entries.`,
);
